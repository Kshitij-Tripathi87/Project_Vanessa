import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../../");
const schemaPath = resolve(root, "packages/shared/schema/protocol-v1.schema.json");
const destination = resolve(root, "apps/android/core/protocol/src/main/kotlin/com/vanessa/protocol/ProtocolMessages.kt");
const fixtureSource = resolve(root, "packages/shared/fixtures/protocol-v1.jsonl");
const fixtureDestination = resolve(root, "apps/android/core/protocol/src/test/resources/protocol-v1.jsonl");
const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const variants = schema.definitions.VanessaProtocolMessage.anyOf;
const resolveRef = (value) => {
  let current = value;
  while (current?.$ref) current = current.$ref.slice(2).split("/").reduce((node, key) => node[key], schema);
  return current;
};
const kotlinType = (property, name) => {
  if (name === "v") return "Int";
  if (name === "id" || name === "type") return "String";
  property = resolveRef(property);
  if (property.anyOf || property.oneOf) {
    const candidates = property.anyOf ?? property.oneOf;
    const concrete = candidates.find((item) => item.type !== "null") ?? candidates[0];
    return kotlinType(concrete, name);
  }
  if (property.const !== undefined) return typeof property.const === "number" ? "Int" : "String";
  if (property.type === "integer" || property.type === "number") return "Long";
  if (property.type === "boolean") return "Boolean";
  if (property.type === "string") return "String";
  if (property.type === "array") return `List<${kotlinType(property.items ?? {})}>`;
  if (property.type === "object") return "JsonObject";
  return "JsonElement";
};
const classes = variants.map((variant) => {
  const props = variant.properties;
  const messageType = props.type.const;
  const className = messageType.split(/[._-]/).map((part) => part[0].toUpperCase() + part.slice(1)).join("");
  const required = new Set(variant.required ?? []);
  const fields = Object.entries(props).filter(([name]) => name !== "type").map(([name, prop]) => {
    const type = kotlinType(prop, name);
    const optional = !required.has(name);
    return `    ${["v", "id", "type"].includes(name) ? "override " : ""}val ${name}: ${type}${optional ? "? = null" : ""}`;
  });
  return `@kotlinx.serialization.Serializable\n@kotlinx.serialization.SerialName("${messageType}")\ndata class ${className}(\n${fields.join(",\n")}\n) : ProtocolMessage`;
});
const content = `// Generated by packages/shared/scripts/generate-kotlin-models.mjs. Do not edit.\npackage com.vanessa.protocol\n\nimport kotlinx.serialization.Serializable\nimport kotlinx.serialization.SerialName\nimport kotlinx.serialization.json.JsonElement\nimport kotlinx.serialization.json.JsonObject\n\n@Serializable\nsealed interface ProtocolMessage { val v: Int; val id: String }\n\n${classes.join("\n\n")}\n`;
await mkdir(dirname(destination), { recursive: true });
await writeFile(destination, content, "utf8");
await mkdir(dirname(fixtureDestination), { recursive: true });
await copyFile(fixtureSource, fixtureDestination);
