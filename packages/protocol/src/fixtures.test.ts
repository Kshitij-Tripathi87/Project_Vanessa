import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { test } from "node:test";
import assert from "node:assert/strict";

import { canonicalize, canonicalizeToBytes } from "./canonicalize.ts";
import { decodeRemoteEnvelope, safeParseRemoteEnvelope, toSignedRemoteEnvelope } from "./envelope.ts";
import { REMOTE_MESSAGE_DIRECTIONS, REMOTE_MESSAGE_TYPES, safeParseRemotePayload } from "./messages.ts";
import { computeKeyId, verifyRemoteEnvelopeSignature } from "./signatures.ts";

/**
 * These fixtures are the cross-language contract. Kotlin and TypeScript both
 * check them, so a disagreement between the two implementations shows up as a
 * failing test on whichever side is wrong rather than as a production
 * signature failure.
 *
 * They are generated by `scripts/generate-fixtures.mjs`, which asserts its own
 * output as it writes. The tests here repeat those assertions from the files, so
 * a stale or hand-edited fixture is caught in CI without running the generator.
 */

const read = (name: string) => readFileSync(new URL(`../fixtures/${name}`, import.meta.url), "utf8");

const canonicalFile = JSON.parse(read("canonical-vectors.json")) as {
  version: number;
  vectors: { name: string; input: unknown; expected: string; canonical: string; sha256: string }[];
};

const signatureFile = JSON.parse(read("signature-vectors.json")) as {
  version: number;
  testOnly: boolean;
  warning: string;
  keyPair: { privateKeyPem: string; publicKeyPem: string };
  keyId: string;
  fingerprint: string;
  vectors: { name: string; note: string; canonicalSignedJson: string; sha256: string; keyId: string; envelope: unknown }[];
};

type WireLine = {
  kind: "valid" | "invalid";
  messageType: string;
  note: string;
  reasonCode?: string;
  envelope?: unknown;
  rawText?: string;
};

const wireLines: WireLine[] = read("protocol-v2.jsonl")
  .split("\n")
  .filter((line) => line.trim().length > 0)
  .map((line) => JSON.parse(line) as WireLine);

/* ------------------------------------------------------------------ *
 * Canonical vectors
 * ------------------------------------------------------------------ */

test("the canonical vector file covers every known disagreement point", () => {
  const names = canonicalFile.vectors.map((vector) => vector.name);
  for (const required of [
    "number-exponent-thresholds",
    "utf16-key-ordering-digits",
    "string-escapes",
    "unicode-passthrough",
    "bare-minus-sign-is-invalid",
    "safe-integer-boundary",
    "null-and-booleans",
    "empty-object-and-array",
    "action-hash-preimage",
  ]) {
    assert.equal(names.includes(required), true, `the vector set is missing ${required}`);
  }
  // The exponent thresholds are the disagreement that matters most: a JSON
  // writer that emits 1E+21 or 0.0000001 produces a different signature.
  const thresholds = canonicalFile.vectors.find((vector) => vector.name === "number-exponent-thresholds");
  assert.ok(thresholds);
  // Exponential form only at 1e21 and below 1e-6: 1e-6 and 9.99e20 stay in
  // fixed form — 9.99e20 as 21 digits — exactly where ECMAScript switches.
  // Negative zero is covered by its own vector.
  assert.equal(thresholds.canonical, '{"a":1e+21,"b":1e-7,"c":0.000001,"d":273.15,"e":999000000000000000000}');
});

test("each canonical vector is reproducible from its input and digest", () => {
  for (const vector of canonicalFile.vectors) {
    assert.equal(canonicalize(vector.input), vector.expected, `${vector.name}: implementation drifted`);
    assert.equal(canonicalize(vector.input), vector.canonical, `${vector.name}: stored canonical text drifted`);
    assert.equal(
      createHash("sha256").update(vector.canonical, "utf8").digest("hex"),
      vector.sha256,
      `${vector.name}: stored digest drifted`,
    );
    assert.deepEqual(Buffer.from(canonicalizeToBytes(vector.input)), Buffer.from(vector.canonical, "utf8"));
  }
});

test("the action-hash preimage vector is a JCS object, not a string", () => {
  const vector = canonicalFile.vectors.find((entry) => entry.name === "action-hash-preimage");
  assert.ok(vector);
  assert.equal(typeof vector.input, "object", "the preimage is the parsed binding object");
  assert.equal(vector.canonical, canonicalize(vector.input));
});

/* ------------------------------------------------------------------ *
 * Signature vectors
 * ------------------------------------------------------------------ */

test("the signature vectors are marked test-only and carry the warning", () => {
  assert.equal(signatureFile.testOnly, true);
  assert.match(signatureFile.warning, /must never be installed on a device/);
  // The throwaway key is public by design; asserting that here makes an
  // accidental substitution of a real key a test failure.
  assert.match(signatureFile.keyPair.privateKeyPem, /-----BEGIN PRIVATE KEY-----/);
  assert.match(signatureFile.keyPair.publicKeyPem, /-----BEGIN PUBLIC KEY-----/);
  assert.equal(computeKeyId(signatureFile.keyPair.publicKeyPem), signatureFile.keyId);
});

test("every message type has a signed vector", () => {
  const names = signatureFile.vectors.map((vector) => vector.name);
  assert.deepEqual([...names].sort(), [...REMOTE_MESSAGE_TYPES].sort());
});

test("each signed vector verifies and its canonical bytes are reproducible", () => {
  const { publicKeyPem } = signatureFile.keyPair;
  for (const vector of signatureFile.vectors) {
    const envelope = safeParseRemoteEnvelope(vector.envelope);
    assert.equal(envelope.success, true, `${vector.name}: the vector is not a valid envelope`);
    if (!envelope.success) continue;

    // The stored canonical bytes are what was signed, and they are derived from
    // the envelope by removing the signature — not by re-serializing the frame.
    assert.equal(
      canonicalize(toSignedRemoteEnvelope(envelope.data)),
      vector.canonicalSignedJson,
      `${vector.name}: canonical signing material drifted`,
    );
    assert.equal(
      createHash("sha256").update(vector.canonicalSignedJson, "utf8").digest("hex"),
      vector.sha256,
      `${vector.name}: stored digest drifted`,
    );
    assert.equal(envelope.data.keyId, vector.keyId, `${vector.name}: the vector names a different key`);
    assert.equal(computeKeyId(publicKeyPem), vector.keyId, `${vector.name}: the key id does not own this vector`);

    const verified = verifyRemoteEnvelopeSignature(publicKeyPem, envelope.data);
    assert.deepEqual(verified, { ok: true }, `${vector.name}: signature failed (${verified.ok ? "" : verified.reason})`);

    // The payload must satisfy its own schema, so these vectors are also input
    // for the schema tests.
    assert.equal(
      safeParseRemotePayload(envelope.data.type, envelope.data.payload).success,
      true,
      `${vector.name}: payload does not match its schema`,
    );
  }
});

/* ------------------------------------------------------------------ *
 * Wire lines
 * ------------------------------------------------------------------ */

/** What the listener would actually do with a line, stage by stage. */
function classify(line: WireLine): { stage: string; detail: string } {
  if (line.rawText !== undefined) {
    const bytes = Buffer.byteLength(line.rawText, "utf8");
    try {
      decodeRemoteEnvelope(Buffer.from(line.rawText, "utf8"));
      return { stage: "decoded", detail: "the frame should not have decoded" };
    } catch (error) {
      return { stage: bytes > 64 * 1024 ? "size" : "decode_error", detail: error instanceof Error ? error.message : String(error) };
    }
  }
  const envelope = safeParseRemoteEnvelope(line.envelope);
  if (!envelope.success) return { stage: "envelope_invalid", detail: envelope.error.issues[0]?.message ?? "envelope" };
  if (line.kind === "invalid") {
    const payload = safeParseRemotePayload(envelope.data.type, envelope.data.payload);
    if (!payload.success) return { stage: "payload_invalid", detail: payload.error.issues[0]?.message ?? "payload" };
  }
  const signature = verifyRemoteEnvelopeSignature(signatureFile.keyPair.publicKeyPem, envelope.data);
  if (!signature.ok) return { stage: "signature_invalid", detail: signature.reason };
  return { stage: "accepted", detail: REMOTE_MESSAGE_DIRECTIONS[envelope.data.type] };
}

const REJECTION_STAGES: Record<string, string[]> = {
  UNSUPPORTED_VERSION: ["envelope_invalid"],
  UNKNOWN_MESSAGE_TYPE: ["envelope_invalid"],
  INVALID_MESSAGE: ["envelope_invalid", "decode_error"],
  MALFORMED_SIGNATURE: ["envelope_invalid"],
  INVALID_PAYLOAD: ["payload_invalid"],
  INVALID_SIGNATURE: ["signature_invalid"],
  PERMISSION_DENIED: ["accepted"],
  PAYLOAD_TOO_LARGE: ["size"],
};

test("the wire file has valid and invalid lines for every documented rejection", () => {
  const valid = wireLines.filter((line) => line.kind === "valid");
  const invalid = wireLines.filter((line) => line.kind === "invalid");
  assert.ok(valid.length >= REMOTE_MESSAGE_TYPES.length, "every message type needs an accepted frame");
  assert.ok(invalid.length >= 8, "each rejection reason needs a frame that produces it");

  const covered = new Set(invalid.map((line) => line.reasonCode));
  for (const reason of Object.keys(REJECTION_STAGES)) {
    assert.equal(covered.has(reason), true, `no frame produces ${reason}`);
  }
});

test("every valid frame is accepted and every invalid frame fails for its stated reason", () => {
  for (const line of wireLines) {
    const result = classify(line);
    const where = `${line.kind} ${line.messageType} (${line.reasonCode ?? "accepted"})`;
    if (line.kind === "valid") {
      assert.equal(result.stage, "accepted", `${where}: ${result.detail}`);
      continue;
    }
    const expected = REJECTION_STAGES[line.reasonCode ?? ""];
    assert.ok(expected, `${where}: no stage is mapped for this reason code`);
    assert.ok(expected.includes(result.stage), `${where} should fail as ${expected.join(" or ")}, got ${result.stage}: ${result.detail}`);
  }
});

test("the invalid frames are rejected at the right layer, not merely somewhere", () => {
  const by = (messageType: string, reasonCode: string) =>
    wireLines.find((line) => line.messageType === messageType && line.reasonCode === reasonCode);

  // A frame the client may not send must be structurally perfect: it is refused
  // by policy, after its signature verifies.
  const wrongDirection = by("server.challenge", "PERMISSION_DENIED");
  assert.ok(wrongDirection);
  const accepted = classify(wrongDirection);
  assert.equal(accepted.stage, "accepted");
  assert.equal(accepted.detail, "server_to_client");

  // The duplicate-member frame is the one that JSON.parse alone cannot catch.
  // `task.submit` also has a non-raw INVALID_MESSAGE line (an extra envelope
  // field), so select the raw-text frame explicitly.
  const duplicate = wireLines.find(
    (line) => line.messageType === "task.submit" && line.reasonCode === "INVALID_MESSAGE" && line.rawText !== undefined,
  );
  assert.ok(duplicate?.rawText);
  assert.equal(JSON.parse(duplicate.rawText as string).v, 2, "JSON.parse keeps the last occurrence");
  assert.match(classify(duplicate).detail, /Duplicate JSON member/);

  // The size rejection happens before any parsing work.
  const oversized = by("task.submit", "PAYLOAD_TOO_LARGE");
  assert.ok(oversized?.rawText);
  assert.equal(classify(oversized).stage, "size");

  // The signature-removed frame never reaches verification.
  const unsigned = by("client.authenticate", "MALFORMED_SIGNATURE");
  assert.ok(unsigned);
  assert.equal(classify(unsigned).stage, "envelope_invalid");
});

test("the wire lines decode from raw text without relying on the stored object", () => {
  // Anything the listener must handle has to be decodable from bytes, so the
  // frames that are structurally valid are re-encoded and re-decoded here.
  // Frames whose envelope itself is schema-invalid (for example v: 1) are
  // covered by the rejection tests instead.
  for (const line of wireLines) {
    if (line.rawText !== undefined || line.envelope === undefined) continue;
    if (!safeParseRemoteEnvelope(line.envelope).success) continue;
    const text = JSON.stringify(line.envelope);
    const decoded = decodeRemoteEnvelope(Buffer.from(text, "utf8"));
    assert.equal(decoded.type, line.messageType);
  }
});
